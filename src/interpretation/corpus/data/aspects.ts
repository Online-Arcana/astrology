const claimsFor = (atomId: string): string[] =>
  aspectClaims.filter((claim) => claim.atomId === atomId).map((claim) => claim.id);

const aspect = (
  id: string,
  displayName: string,
  plainEnglish: string,
  doNotInfer: readonly string[] = [],
): CorpusAtom => ({
  id: `aspect.${id}`,
  kind: "relation",
  displayName,
  plainEnglish,
  aliases: [displayName],
  internalIds: [id.replaceAll("-", "_")],
  claimIds: claimsFor(`aspect.${id}`),
  doNotInfer: [...doNotInfer],
  relatedAtomIds: [],
  sourceIds: [source],
  reviewStatus: "approved",
});

